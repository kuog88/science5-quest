/* 露與霜實驗室：調整杯子外壁溫度，觀察杯外出現什麼 */
G.types.dewlab = function (lv, area, api) {
  area.innerHTML = '<div class="panel sim"><svg viewBox="0 0 400 240"></svg>' +
    '<div class="slider">杯子溫度 <input type="range" min="-10" max="30" step="1" value="28"><b class="tv"></b></div>' +
    '<div class="msg"></div><ul class="tasks"></ul><div class="row"><button class="btn go" disabled>觀察完成，下一步 ➜</button></div></div>';
  var svg = G.$('svg', area), msg = G.$('.msg', area), inp = G.$('input', area);
  var mark = G.labTasks(area, [
    { k: 'dry', t: '杯子不夠冷：外面乾乾的' },
    { k: 'dew', t: '杯子變冷（0 ℃以上）：外面出現什麼？' },
    { k: 'frost', t: '杯子低於 0 ℃：外面出現什麼？' }
  ], function () { G.thenQuiz(lv, area, api, '根據剛才的觀察回答問題！'); });
  function draw() {
    var t = +inp.value, st = t >= 20 ? 'dry' : t >= 0 ? 'dew' : 'frost';
    G.$('.tv', area).textContent = t + ' ℃';
    var fill = st === 'frost' ? '#e3f2fd' : '#b3e5fc', s = '';
    if (st === 'dew') for (var i = 0; i < 16; i++) s += '<ellipse cx="' + (152 + (i * 37) % 96) + '" cy="' + (78 + (i * 23) % 120) + '" rx="4" ry="6" fill="#4fc3f7" stroke="#0288d1"/>';
    if (st === 'frost') for (var j = 0; j < 22; j++) { var x = 150 + (j * 29) % 100, y = 74 + (j * 41) % 126; s += '<text x="' + x + '" y="' + y + '" font-size="14" fill="#90a4ae">✳</text>'; }
    svg.innerHTML = '<rect width="400" height="240" rx="14" fill="#fffde7"/>' +
      '<text x="20" y="30" font-size="15" fill="#8d6e63">室溫 30 ℃・空氣中有看不見的水蒸氣</text>' +
      [40, 80, 320, 360].map(function (x, k) { return '<text x="' + x + '" y="' + (90 + k * 30) + '" font-size="14" fill="#bdbdbd">·∘</text>'; }).join('') +
      '<path d="M140 60 L150 210 H250 L260 60Z" fill="' + fill + '" stroke="#78909c" stroke-width="3"/>' +
      (t < 10 ? '<text x="200" y="140" font-size="30" text-anchor="middle">🧊🧊</text>' : '') + s +
      '<rect x="120" y="210" width="160" height="10" rx="4" fill="#a1887f"/>';
    msg.innerHTML = st === 'dry' ? '杯子外面<b>乾乾的</b>，還不夠冷。' :
      st === 'dew' ? '💧 杯子外面出現<b>小水珠</b>！水蒸氣遇冷變成<b>液態的水</b>（像「露」）。' :
        '❄️ 杯子外面出現<b>白白的冰晶</b>！水蒸氣遇冷直接變成<b>固態的冰</b>（像「霜」）。';
    mark(st);
  }
  inp.addEventListener('input', draw);
  draw();
};

